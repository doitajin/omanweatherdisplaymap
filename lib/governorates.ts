// Helper to convert geographic (lat, lon) to 3D scene (x, z)
export function geoTo3D(lat: number, lon: number): [number, number] {
  const CENTER_LAT = 21.8;
  const CENTER_LON = 56.4;
  const x = (lon - CENTER_LON) * 2.35;
  const z = -(lat - CENTER_LAT) * 2.55;
  return [x, z];
}
